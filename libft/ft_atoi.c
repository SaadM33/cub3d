int	ft_atoi(const char *nptr)
{
	char	*s;
	int		res;
	int		sign;

	s = (char *)nptr;
	res = 0;
	sign = 1;
	while ((*s <= 13 && *s >= 9) || *s == ' ')
		s++;
	if (*s == '-' || *s == '+')
	{
		if (*s == '-')
		{
			sign *= -1;
		}
		s++;
	}
	while (*s <= '9' && *s >= '0')
	{
		res = (res * 10) + (*s - 48);
		s++;
	}
	return (res * sign);
}
